// Edabit - Bitwise Operations

function bitwiseAND(n1, n2) {
    return n1 & n2;
}

function bitwiseOR(n1, n2) {
    return n1 | n2;
}

function bitwiseXOR(n1, n2) {
    return n1 ^ n2;
}

// Pruebas 
console.log(bitwiseAND(7, 12)); // Resultado: 4
console.log(bitwiseOR(7, 12));  // Resultado: 15
console.log(bitwiseXOR(7, 12)); // Resultado: 11
